	if(typeof id === "undefined"){
		let item_val=$("#item").find(":selected").val().split("^");
		item_id=item_val[0];
		batch_code=$("#batch_code_val").find(":selected").val();
	}else{
	 item_id=id;
	 batch_code=$("#batch_code_val").find(":selected").val();	
	}

	

	$.ajax({

            url: 'get_json_data_for_optical.php?flag=29',

			type: 'POST',

			dataType: 'json',

			data: "item_id="+item_id+"&batch_code="+batch_code,

